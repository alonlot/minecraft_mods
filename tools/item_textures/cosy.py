SPRITES = {}


def add(name, grid, pal, dy=0):
    """dy moves the drawing down (or up) that many rows, to centre it on the 16x16 canvas."""
    rows = [r.strip() for r in grid.strip(chr(10)).splitlines() if r.strip()]
    blank = "." * 16
    if dy > 0:
        rows = [blank] * dy + rows[:-dy]
    elif dy < 0:
        rows = rows[-dy:] + [blank] * -dy
    SPRITES[name] = sprite(chr(10).join(rows), pal)



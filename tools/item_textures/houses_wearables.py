def overlay(base, top):
    b = [r.strip() for r in base.strip("\n").splitlines() if r.strip()]
    t = [r.strip() for r in top.strip("\n").splitlines() if r.strip()]
    return "\n".join("".join(tc if tc != "." else bc for bc, tc in zip(br, tr)) for br, tr in zip(b, t))



def house(name):
    glyph, m, fld, eye, accent = HOUSES[name]
    spec, light, mid, dark, kl, kd = m
    pal = {".": None, "K": kl, "k": kd, "W": spec, "R": light, "r": mid, "q": dark,
           "F": fld[0], "f": fld[1], "d": fld[2], "A": light, "B": mid, "C": dark, "e": eye}
    if accent:
        pal["w"] = accent
    return sprite(overlay(SHIELD, glyph), pal)



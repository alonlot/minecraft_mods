"""Generate src/main/java/com/hogwartsmagic/portrait/FatLadyLines.java from fat_lady_lines.json + portraits/fat_lady.json.

Line lengths come from the installed sounds (make_voice.py / lipsync_dub.py write them into the meta json);
a line with no sound yet gets 5 s so the server's cooldowns still work.
"""
import json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))
spec = json.load(open(os.path.join(HERE, "fat_lady_lines.json")))
meta_path = os.path.join(ROOT, "src/main/resources/assets/hogwartsmagic/portraits/fat_lady.json")
meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {"lines": {}}

reactions = list(dict.fromkeys(l["reaction"] for l in spec["lines"]))
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
rows = []
for l in spec["lines"]:
    secs = meta["lines"].get(l["key"], {}).get("seconds", 5.0)
    clip = f'"{l["clip"]}"' if l.get("clip") else "null"
    rows.append(f'            new Line("{l["key"]}", Reaction.{l["reaction"]}, Mood.{l["mood"]}, {secs}f, {clip},\n'
                f'                    "{esc(l["text"])}")')

ROWS = ",\n".join(rows)
java = f"""package com.hogwartsmagic.portrait;

import java.util.List;

/**
 * Every line the Fat Lady can say. GENERATED by tools/living_portraits/gen_lines_java.py from
 * tools/living_portraits/fat_lady_lines.json; edit the json and regenerate, never this file.
 * Each line's sound is hogwartsmagic:portrait.fat_lady.&lt;key&gt;; a line with a clip plays that Flow video
 * (textures/entity/portrait/fat_lady/clips/&lt;clip&gt;/) instead of the puppet.
 */
public final class FatLadyLines {{
    private FatLadyLines() {{
    }}

    /** What set her off. */
    public enum Reaction {{
        {", ".join(reactions)}
    }}

    /** Which face the puppet wears while she says it. */
    public enum Mood {{
        NEUTRAL, HAPPY, CROSS, SCARED
    }}

    public record Line(String key, Reaction reaction, Mood mood, float seconds, String clip, String text) {{
        public boolean isVideo() {{
            return clip != null;
        }}
    }}

    public static final List<Line> LINES = List.of(
{ROWS});

    /** Index into LINES, or -1. */
    public static int indexOf(String key) {{
        for (int i = 0; i < LINES.size(); i++) {{
            if (LINES.get(i).key().equals(key)) {{
                return i;
            }}
        }}
        return -1;
    }}

    public static Line get(int index) {{
        return index >= 0 && index < LINES.size() ? LINES.get(index) : null;
    }}
}}
"""
out = os.path.join(ROOT, "src/main/java/com/hogwartsmagic/portrait/FatLadyLines.java")
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, "w", newline="\n").write(java)
print("wrote", out, len(rows), "lines,", len(reactions), "reactions")

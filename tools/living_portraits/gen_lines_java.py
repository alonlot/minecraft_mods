"""Generate src/main/java/com/hogwartsmagic/portrait/PortraitLines.java from every tools/living_portraits/*_lines.json.

Each <portrait>_lines.json becomes one list (FAT_LADY, SIR_CADOGAN, ...). Line lengths come from the installed
sounds (make_voice.py / make_clip.py write them into assets/hogwartsmagic/portraits/<portrait>.json); a line
with no sound yet gets 5 s so the server's cooldowns still work. Reactions are the union over all portraits,
in first-seen order (fat_lady first, so her ordinals never move).
"""
import glob, json, os

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
HERE = os.path.dirname(os.path.abspath(__file__))
ORDER = ["fat_lady"]  # older portraits first keep reaction order stable; the rest follow alphabetically

names = sorted((os.path.basename(p)[:-len("_lines.json")] for p in glob.glob(os.path.join(HERE, "*_lines.json"))),
               key=lambda n: (ORDER.index(n) if n in ORDER else len(ORDER), n))
esc = lambda s: s.replace("\\", "\\\\").replace('"', '\\"')
reactions, lists = [], []
for name in names:
    spec = json.load(open(os.path.join(HERE, f"{name}_lines.json")))
    meta_path = os.path.join(ROOT, f"src/main/resources/assets/hogwartsmagic/portraits/{name}.json")
    meta = json.load(open(meta_path)) if os.path.exists(meta_path) else {"lines": {}}
    rows = []
    for l in spec["lines"]:
        if l["reaction"] not in reactions:
            reactions.append(l["reaction"])
        secs = meta.get("lines", {}).get(l["key"], {}).get("seconds", 5.0)
        clip = f'"{l["clip"]}"' if l.get("clip") else "null"
        rows.append(f'            new Line("{name}", "{l["key"]}", Reaction.{l["reaction"]}, Mood.{l["mood"]}, {secs}f,\n'
                    f'                    {clip}, "{esc(l["text"])}")')
    body = ",\n".join(rows)
    lists.append(f"    public static final List<Line> {name.upper()} = List.of(\n{body});\n")

BY_ID = "\n".join(f'        if (id.equals("{n}")) {{\n            return {n.upper()};\n        }}' for n in names)
LISTS = "\n".join(lists)
java = f"""package com.hogwartsmagic.portrait;

import java.util.List;

/**
 * Every line every living portrait can say. GENERATED by tools/living_portraits/gen_lines_java.py from
 * tools/living_portraits/*_lines.json; edit the json and regenerate, never this file.
 * A line's sound is hogwartsmagic:portrait.&lt;portrait&gt;.&lt;key&gt;; a line with a clip plays that Flow video
 * (textures/entity/portrait/&lt;portrait&gt;/clips/&lt;clip&gt;/) instead of the puppet.
 */
public final class PortraitLines {{
    private PortraitLines() {{
    }}

    /** What set them off. A portrait without lines for a reaction simply never reacts to it. */
    public enum Reaction {{
        {", ".join(reactions)}
    }}

    /** Which face the puppet wears while saying it. */
    public enum Mood {{
        NEUTRAL, HAPPY, CROSS, SCARED
    }}

    public record Line(String portrait, String key, Reaction reaction, Mood mood, float seconds, String clip,
                       String text) {{
        public boolean isVideo() {{
            return clip != null;
        }}

        /** Path of the SoundEvent id, e.g. portrait.fat_lady.greet_1. */
        public String soundPath() {{
            return "portrait." + portrait + "." + key;
        }}
    }}

{LISTS}
    /** The lines of the portrait with this id (e.g. "fat_lady"), or an empty list. */
    public static List<Line> forPortrait(String id) {{
{BY_ID}
        return List.of();
    }}
}}
"""
out = os.path.join(ROOT, "src/main/java/com/hogwartsmagic/portrait/PortraitLines.java")
open(out, "w", newline="\n").write(java)
print("wrote", out, "portraits:", names, "reactions:", len(reactions))
